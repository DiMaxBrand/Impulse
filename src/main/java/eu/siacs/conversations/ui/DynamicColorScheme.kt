/**
 * Samsung One UI 8.5 generates a much darker tone for surfaceContainerHigh than the M3 spec
 * expects (~tone 70 vs. the standard ~92). In light mode that made incoming chat bubbles a dark
 * grey, and later the same happened to the chat list's search bar, which uses the same role.
 * Remap it to the lighter surfaceContainerLow tier on Samsung. Every Compose theme that draws
 * surfaceContainerHigh must go through this.
 */
fun ColorScheme.withSamsungSurfaceFix(isDark: Boolean): ColorScheme =
    if (Build.MANUFACTURER.equals("samsung", ignoreCase = true) && !isDark) {
        copy(surfaceContainerHigh = surfaceContainerLow)
    } else this

private var cachedKey: Triple<Boolean, Boolean, Int>? = null
private var cachedScheme: ColorScheme? = null

/**
 * Colour scheme for every Compose screen.
 *
 * - "Dynamic colors" on and API 31+: the wallpaper-derived Material You scheme.
 * - Dynamic off with the default (green) accent: the app's own green palette, exactly the one the
 *   View screens have always used (res/values/colors-themed.xml), so both stacks look the same.
 * - Dynamic off with another accent: a scheme generated from that colour, deliberately calm (see
 *   [tunedSeed]) and generated by the same algorithm Material applies to the View screens.
 */
fun dynamicOrStaticColorScheme(context: Context, isDark: Boolean): ColorScheme {
    val settings = AppSettings(context)
    val dynamic = settings.isDynamicColorsDesired && Build.VERSION.SDK_INT >= Build.VERSION_CODES.S
    val seed = settings.accentSeed
    val key = Triple(isDark, dynamic, if (dynamic) 0 else seed)
    // Dynamic schemes depend on the wallpaper, which can change: never cache those.
    if (!dynamic && key == cachedKey) cachedScheme?.let { return it }
    val scheme =
        if (dynamic) {
            if (isDark) dynamicDarkColorScheme(context) else dynamicLightColorScheme(context)
        } else if (seed == AppSettings.DEFAULT_ACCENT_SEED) {
            appGreenColorScheme(context, isDark) ?: seedColorScheme(seed, isDark)
        } else {
            seedColorScheme(seed, isDark)
        }
    if (!dynamic) {
        cachedKey = key
        cachedScheme = scheme
    }
    return scheme
}

/** Material's content-based generation keeps the seed's full saturation, which tints whole
 * screens. Capping chroma keeps the hue and makes the result a tint, not a paint job. */
fun tunedSeed(seed: Int): Int {
    val hct = Hct.fromInt(seed)
    return Hct.from(hct.hue, minOf(hct.chroma, 36.0), hct.tone).toInt()
}

/** The View screens' green palette as a Compose scheme; null if the resources are missing. */
private fun appGreenColorScheme(context: Context, isDark: Boolean): ColorScheme? {
    val mode = if (isDark) "dark" else "light"
    val res = context.resources
    fun c(name: String): Color? {
        val id = res.getIdentifier("md_theme_${mode}_$name", "color", context.packageName)
        return if (id == 0) null else Color(context.getColor(id))
    }
    val primary = c("primary") ?: return null
    val onPrimary = c("onPrimary") ?: return null
    val secondary = c("secondary") ?: return null
    val onSecondary = c("onSecondary") ?: return null
    val secondaryContainer = c("secondaryContainer") ?: return null
    val onSecondaryContainer = c("onSecondaryContainer") ?: return null
    val tertiary = c("tertiary") ?: return null
    val onTertiary = c("onTertiary") ?: return null
    val tertiaryContainer = c("tertiaryContainer") ?: return null
    val onTertiaryContainer = c("onTertiaryContainer") ?: return null
    val surface = c("surface") ?: return null
    val neutral = com.google.android.material.color.utilities.TonalPalette.fromInt(surface.toArgb())
    fun n(tone: Int) = Color(neutral.tone(tone))
    fun tonal(color: Color, tone: Int) =
        Color(com.google.android.material.color.utilities.TonalPalette.fromInt(color.toArgb()).tone(tone))
    return ColorScheme(
        primary = primary,
        onPrimary = onPrimary,
        // Calm container, same family as the secondary one (the mic button's): our own bubbles
        // and other "primary container" surfaces were far too loud in the full-strength green.
        primaryContainer = secondaryContainer,
        onPrimaryContainer = onSecondaryContainer,
        inversePrimary = c("inversePrimary") ?: primary,
        secondary = secondary,
        onSecondary = onSecondary,
        secondaryContainer = secondaryContainer,
        onSecondaryContainer = onSecondaryContainer,
        tertiary = tertiary,
        onTertiary = onTertiary,
        tertiaryContainer = tertiaryContainer,
        onTertiaryContainer = onTertiaryContainer,
        background = c("background") ?: surface,
        onBackground = c("onBackground") ?: Color.Black,
        surface = surface,
        onSurface = c("onSurface") ?: Color.Black,
        surfaceVariant = c("surfaceVariant") ?: surface,
        onSurfaceVariant = c("onSurfaceVariant") ?: Color.Black,
        surfaceTint = primary,
        inverseSurface = c("inverseSurface") ?: Color.Black,
        inverseOnSurface = c("inverseOnSurface") ?: Color.White,
        error = c("error") ?: Color.Red,
        onError = c("onError") ?: Color.White,
        errorContainer = c("errorContainer") ?: Color.Red,
        onErrorContainer = c("onErrorContainer") ?: Color.Black,
        outline = c("outline") ?: Color.Gray,
        outlineVariant = c("outlineVariant") ?: Color.LightGray,
        scrim = Color.Black,
        surfaceBright = n(if (isDark) 24 else 98),
        surfaceDim = n(if (isDark) 6 else 87),
        surfaceContainerLowest = n(if (isDark) 4 else 100),
        surfaceContainerLow = n(if (isDark) 10 else 96),
        surfaceContainer = n(if (isDark) 12 else 94),
        surfaceContainerHigh = n(if (isDark) 17 else 92),
        surfaceContainerHighest = n(if (isDark) 22 else 90),
        primaryFixed = tonal(primary, 90),
        primaryFixedDim = tonal(primary, 80),
        onPrimaryFixed = tonal(primary, 10),
        onPrimaryFixedVariant = tonal(primary, 30),
        secondaryFixed = tonal(secondary, 90),
        secondaryFixedDim = tonal(secondary, 80),
        onSecondaryFixed = tonal(secondary, 10),
        onSecondaryFixedVariant = tonal(secondary, 30),
        tertiaryFixed = tonal(tertiary, 90),
        tertiaryFixedDim = tonal(tertiary, 80),
        onTertiaryFixed = tonal(tertiary, 10),
        onTertiaryFixedVariant = tonal(tertiary, 30),
    )
}

/** The scheme an accent swatch stands for, exactly as the app would apply it. */
fun accentPreviewScheme(context: Context, seed: Int, isDark: Boolean): ColorScheme =
    if (seed == AppSettings.DEFAULT_ACCENT_SEED) {
        appGreenColorScheme(context, isDark) ?: seedColorScheme(seed, isDark)
    } else {
        seedColorScheme(seed, isDark)
    }

/** Builds a full Compose [ColorScheme] from a single seed colour. */
fun seedColorScheme(seed: Int, isDark: Boolean): ColorScheme {
    val scheme: DynamicScheme = SchemeContent(Hct.fromInt(tunedSeed(seed)), isDark, 0.0)
    val m = MaterialDynamicColors()
    fun DynamicColor.c() = Color(getArgb(scheme))
    return ColorScheme(
        primary = m.primary().c(),
        onPrimary = m.onPrimary().c(),
        primaryContainer = m.primaryContainer().c(),
        onPrimaryContainer = m.onPrimaryContainer().c(),
        inversePrimary = m.inversePrimary().c(),
        secondary = m.secondary().c(),
        onSecondary = m.onSecondary().c(),
        secondaryContainer = m.secondaryContainer().c(),
        onSecondaryContainer = m.onSecondaryContainer().c(),
        tertiary = m.tertiary().c(),
        onTertiary = m.onTertiary().c(),
        tertiaryContainer = m.tertiaryContainer().c(),
        onTertiaryContainer = m.onTertiaryContainer().c(),
        background = m.background().c(),
        onBackground = m.onBackground().c(),
        surface = m.surface().c(),
        onSurface = m.onSurface().c(),
        surfaceVariant = m.surfaceVariant().c(),
        onSurfaceVariant = m.onSurfaceVariant().c(),
        surfaceTint = m.primary().c(),
        inverseSurface = m.inverseSurface().c(),
        inverseOnSurface = m.inverseOnSurface().c(),
        error = m.error().c(),
        onError = m.onError().c(),
        errorContainer = m.errorContainer().c(),
        onErrorContainer = m.onErrorContainer().c(),
        outline = m.outline().c(),
        outlineVariant = m.outlineVariant().c(),
        scrim = Color.Black,
        surfaceBright = m.surfaceBright().c(),
        surfaceDim = m.surfaceDim().c(),
        surfaceContainer = m.surfaceContainer().c(),
        surfaceContainerHigh = m.surfaceContainerHigh().c(),
        surfaceContainerHighest = m.surfaceContainerHighest().c(),
        surfaceContainerLow = m.surfaceContainerLow().c(),
        surfaceContainerLowest = m.surfaceContainerLowest().c(),
        primaryFixed = m.primaryFixed().c(),
        primaryFixedDim = m.primaryFixedDim().c(),
        onPrimaryFixed = m.onPrimaryFixed().c(),
        onPrimaryFixedVariant = m.onPrimaryFixedVariant().c(),
        secondaryFixed = m.secondaryFixed().c(),
        secondaryFixedDim = m.secondaryFixedDim().c(),
        onSecondaryFixed = m.onSecondaryFixed().c(),
        onSecondaryFixedVariant = m.onSecondaryFixedVariant().c(),
        tertiaryFixed = m.tertiaryFixed().c(),
        tertiaryFixedDim = m.tertiaryFixedDim().c(),
        onTertiaryFixed = m.onTertiaryFixed().c(),
        onTertiaryFixedVariant = m.onTertiaryFixedVariant().c(),
    )
}
